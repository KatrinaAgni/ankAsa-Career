alter table public.conference
  add column if not exists penyelenggara text,
  add column if not exists deskripsi text,
  add column if not exists biaya text,
  add column if not exists sumber text not null default 'manual',
  add column if not exists source_url text,
  add column if not exists external_id text,
  add column if not exists last_synced_at timestamptz,
  add column if not exists status text not null default 'published'
    check (status in ('published', 'pending', 'archived')),
  add column if not exists updated_at timestamptz not null default now();

create unique index if not exists conference_source_external_uidx
  on public.conference (sumber, external_id);

create index if not exists conference_status_tanggal_idx
  on public.conference (status, tanggal_mulai);

create table if not exists public.sync_logs (
  id bigint generated by default as identity primary key,
  source text not null,
  fetched int not null default 0,
  inserted int not null default 0,
  updated int not null default 0,
  skipped int not null default 0,
  status text not null default 'running'
    check (status in ('running', 'success', 'error')),
  error text,
  started_at timestamptz not null default now(),
  finished_at timestamptz
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.users
    where id::text = auth.uid()::text
      and tipe_akun::text in ('admin', 'superadmin')
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists conference_set_updated_at on public.conference;
create trigger conference_set_updated_at
  before update on public.conference
  for each row
  execute function public.set_updated_at();

alter table public.conference enable row level security;

do $$
declare
  policy_row record;
begin
  for policy_row in
    select policyname
    from pg_policies
    where schemaname = 'public' and tablename = 'conference'
  loop
    execute format('drop policy %I on public.conference', policy_row.policyname);
  end loop;
end;
$$;

create policy "conference_public_read"
  on public.conference for select to anon
  using (status = 'published');

create policy "conference_auth_read"
  on public.conference for select to authenticated
  using (status = 'published' or public.is_admin());

create policy "conference_admin_insert"
  on public.conference for insert to authenticated
  with check (public.is_admin());

create policy "conference_admin_update"
  on public.conference for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create policy "conference_admin_delete"
  on public.conference for delete to authenticated
  using (public.is_admin());

